package br.edu.chat.persistence.jdbc;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

import br.edu.chat.model.Mensagem;
import br.edu.chat.model.Usuario;
import br.edu.chat.persistence.MensagemRepository;
import br.edu.chat.persistence.PersistenciaException;

/** Implementa a persistência das mensagens usando JDBC e H2. */
public final class JdbcMensagemRepository implements MensagemRepository {

    private static final String CRIAR_TABELA = """
            CREATE TABLE IF NOT EXISTS mensagens (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                remetente VARCHAR NOT NULL,
                conteudo VARCHAR NOT NULL,
                horario TIMESTAMP NOT NULL
            )
            """;
    private static final String INSERIR = """
            INSERT INTO mensagens (remetente, conteudo, horario) VALUES (?, ?, ?)
            """;
    private static final String CONSULTAR = """
            SELECT remetente, conteudo, horario
            FROM mensagens
            ORDER BY horario ASC, id ASC
            """;

    private final ConnectionFactory connectionFactory;

    public JdbcMensagemRepository(ConnectionFactory connectionFactory) {
        this.connectionFactory = Objects.requireNonNull(connectionFactory,
                "A fábrica de conexões não pode ser nula.");
        inicializarTabela();
    }

    @Override
    public void salvar(Mensagem mensagem) {
        Objects.requireNonNull(mensagem, "A mensagem não pode ser nula.");

        try (Connection conexao = connectionFactory.abrir();
             PreparedStatement comando = conexao.prepareStatement(INSERIR)) {
            comando.setString(1, mensagem.getRemetente().getNome());
            comando.setString(2, mensagem.getConteudo());
            comando.setTimestamp(3, Timestamp.valueOf(mensagem.getHorario()));
            comando.executeUpdate();
        } catch (SQLException exception) {
            throw new PersistenciaException("Não foi possível salvar a mensagem.", exception);
        }
    }

    @Override
    public List<Mensagem> listarHistorico() {
        List<Mensagem> mensagens = new ArrayList<>();

        try (Connection conexao = connectionFactory.abrir();
             PreparedStatement comando = conexao.prepareStatement(CONSULTAR);
             ResultSet resultados = comando.executeQuery()) {
            while (resultados.next()) {
                mensagens.add(new Mensagem(
                        new Usuario(resultados.getString("remetente")),
                        resultados.getString("conteudo"),
                        resultados.getTimestamp("horario").toLocalDateTime()));
            }
            return mensagens;
        } catch (SQLException | RuntimeException exception) {
            if (exception instanceof PersistenciaException persistenciaException) {
                throw persistenciaException;
            }
            throw new PersistenciaException("Não foi possível consultar o histórico.", exception);
        }
    }

    private void inicializarTabela() {
        try (Connection conexao = connectionFactory.abrir();
             Statement comando = conexao.createStatement()) {
            comando.execute(CRIAR_TABELA);
        } catch (SQLException exception) {
            throw new PersistenciaException("Não foi possível inicializar a tabela de mensagens.", exception);
        }
    }
}
